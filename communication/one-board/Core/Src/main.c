/* Both cells accept everything: one filter bank per controller, mask mode
 * with a zero mask, so no ID is ever rejected. Filtering by ID happens in
 * software instead, where it can be read at a glance - there are only two
 * IDs on this bus.
 *
 * The bank split is not optional. CAN1 and CAN2 share one bank array;
 * SlaveStartFilterBank draws the line between them, and a CAN2 filter must
 * live at or above it or it is silently ignored. Bank 0 for CAN1, bank 14
 * for CAN2, boundary at 14.
 *
 * Split out of MX_CANx_Init() on purpose: node1.c and node2sim.c call this
 * again after re-initialising a controller that failed to start, and that
 * recovery would be pointless without the filter and the notification. */
void Can_Setup(void)
{
  CAN_FilterTypeDef f = {0};
  f.FilterIdHigh         = 0x0000;
  f.FilterIdLow          = 0x0000;
  f.FilterMaskIdHigh     = 0x0000;
  f.FilterMaskIdLow      = 0x0000;
  f.FilterFIFOAssignment = CAN_FILTER_FIFO0;
  f.FilterMode           = CAN_FILTERMODE_IDMASK;
  f.FilterScale          = CAN_FILTERSCALE_32BIT;
  f.FilterActivation     = CAN_FILTER_ENABLE;
  f.SlaveStartFilterBank = 14;

  /* Skipping a controller that is already running matters because the
   * recovery paths call this again for whichever cell failed: starting an
   * already-LISTENING cell returns HAL_ERROR and leaves NOT_READY stuck in
   * its ErrorCode, which the diagnostics then print for a controller that
   * is in fact perfectly healthy. */
  if (hcan1.State != HAL_CAN_STATE_LISTENING)
  {
    f.FilterBank = 0;
    (void)HAL_CAN_ConfigFilter(&hcan1, &f);
    /* Return value ignored on purpose: a cell that cannot start yet (bus
     * held dominant at power-up) must not stall the boot. Node1_Init()
     * prints the INAK verdict, and the recovery path retries twice a
     * second until the bus goes quiet. */
    (void)HAL_CAN_Start(&hcan1);
    (void)HAL_CAN_ActivateNotification(&hcan1, CAN_IT_RX_FIFO0_MSG_PENDING);
  }

  if (hcan2.State != HAL_CAN_STATE_LISTENING)
  {
    f.FilterBank = 14;
    (void)HAL_CAN_ConfigFilter(&hcan2, &f);
    (void)HAL_CAN_Start(&hcan2);
    (void)HAL_CAN_ActivateNotification(&hcan2, CAN_IT_RX_FIFO0_MSG_PENDING);
  }
}

/* Both CAN cells land here, dispatched by instance. Using HAL's callback
 * rather than editing the two CAN*_RX0_IRQHandler bodies keeps all of this
 * out of CubeMX-owned code, so a future regeneration cannot silently drop
 * it. Both handlers only copy the frame and set a flag; the work happens
 * in the main loop. */
void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan)
{
  if (hcan->Instance == CAN1)
  {
    Node1_HandleCanRx();
  }
  else if (hcan->Instance == CAN2)
  {
    Node2Sim_HandleCanRx();
  }
}

/* TIM2 at 50 ms is Node 1's send cadence - the one timing the practice
 * actually grades. Node 2's 20 ms comes off SysTick inside
 * Node2Sim_Periodic() instead; it is only a test fixture, and keeping the
 * two cadences on separate clocks stops them marching in lockstep. */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM2)
  {
    Node1_OnTimerTick();
  }
}

